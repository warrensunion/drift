"""Export the trained model to public/model/drift.onnx (opset 17, input `x` [N,10]
float32 with a dynamic batch axis, outputs `mu`, `log_sigma`), verify it with
onnxruntime against PyTorch, and write tests/fixtures/onnx-ref.json."""
import json

import numpy as np
import onnx
import onnxruntime as ort
import torch

from common_train import (MODEL_DIR, NAMES, OUT, PUBLIC, ROOT, features, load_model, load_pairs,
                          masks, predict, read_tile, sample, save_json)

ONNX_PATH = MODEL_DIR / "drift.onnx"
FIXTURE = ROOT / "tests" / "fixtures" / "onnx-ref.json"


def export(model):
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    dummy = torch.zeros(4, 10)
    kw = dict(input_names=["x"], output_names=["mu", "log_sigma"], opset_version=17)
    try:
        torch.onnx.export(model, (dummy,), str(ONNX_PATH), dynamo=False,
                          dynamic_axes={"x": {0: "N"}, "mu": {0: "N"}, "log_sigma": {0: "N"}}, **kw)
        how = "torchscript exporter"
    except Exception as e:  # noqa: BLE001  (legacy exporter removed -> dynamo)
        print("legacy exporter failed:", repr(e)[:200])
        torch.onnx.export(model, (dummy,), str(ONNX_PATH), dynamo=True, external_data=False,
                          dynamic_shapes={"x": {0: torch.export.Dim("N")}}, **kw)
        how = "dynamo exporter"
    m = onnx.load(str(ONNX_PATH))
    onnx.checker.check_model(m)
    print("exported with", how, "opset", [o.version for o in m.opset_import],
          "bytes", ONNX_PATH.stat().st_size)
    return how


def main():
    model, ck = load_model()
    how = export(model)
    d = load_pairs()
    split = {k: np.array(v) for k, v in json.loads((OUT / "split.json").read_text()).items()}
    te = np.where(masks(d, split)["test"])[0]

    # onnxruntime vs PyTorch on all test rows
    sess = ort.InferenceSession(str(ONNX_PATH), providers=["CPUExecutionProvider"])
    X = d["X"][te]
    mu_t, ls_t = predict(model, X)
    mu_o, ls_o = sess.run(["mu", "log_sigma"], {"x": X})
    dmax = float(max(np.abs(mu_o - mu_t).max(), np.abs(ls_o - ls_t).max()))
    print(f"onnxruntime vs torch on {len(te)} test rows: max abs diff {dmax:.2e}")
    assert dmax < 1e-4

    rng = np.random.default_rng(64)
    rows = np.sort(rng.choice(te, 64, replace=False))
    Xr = d["X"][rows]
    mu, ls = predict(model, Xr)
    rec = []
    for i, r in enumerate(rows):
        rec.append(dict(
            lat=float(d["lat"][r]), lon=float(d["lon"][r]), u_cur=float(d["u_cur"][r]),
            v_cur=float(d["v_cur"][r]), u_wind=float(d["u_wind"][r]), v_wind=float(d["v_wind"][r]),
            doy=float(d["doy"][r]), windage=float(d["windage"][r]),
            features=[float(v) for v in Xr[i]],
            mu=[float(v) for v in mu[i]], log_sigma=[float(v) for v in ls[i]]))
    # Field samples: 16 of the rows (Python sampler on the shipped tiles)
    wind = read_tile(PUBLIC / "wind" / "clim.bin")
    samples = []
    for r in rows[::4]:
        m = int(d["month"][r])
        lon, lat = float(d["lon"][r]), float(d["lat"][r])
        cu, cv = sample(read_tile(PUBLIC / "currents" / f"clim-{m:02d}.bin"), lon, lat)
        wu, wv = sample(wind, lon, lat, frame=m - 1)
        samples.append(dict(month=m, lon=lon, lat=lat, current=[float(cu[0]), float(cv[0])],
                            windFrame=m - 1, wind=[float(wu[0]), float(wv[0])]))
    save_json(FIXTURE, dict(
        note="64 random TEST rows: raw feature inputs, Python features (float32), PyTorch outputs; "
             "samples: Python common.sample on public/data tiles (current frame 0 of clim-MM.bin, "
             "wind frame month-1 of wind/clim.bin). Generated by scripts/train/export.py.",
        featureNames=NAMES, exporter=how, rows=rec, samples=samples))
    print("wrote", FIXTURE)


if __name__ == "__main__":
    main()
